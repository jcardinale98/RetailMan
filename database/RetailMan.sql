    (
        p_product_id IN PRODUCTOS_GTIN.product_id%TYPE,
        p_gtin1      IN PRODUCTOS_GTIN.gtin%TYPE,
        p_gtin2      IN PRODUCTOS_GTIN.gtin%TYPE DEFAULT NULL,
        p_gtin3      IN PRODUCTOS_GTIN.gtin%TYPE DEFAULT NULL
    )
    IS

        PROCEDURE PD_INSERTAR_GTIN_INTERNO
        (
            p_gtin IN PRODUCTOS_GTIN.gtin%TYPE
