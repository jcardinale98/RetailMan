    --------------------------------------------------------
    -- FUNCIÓN PRIVADA
    -- Verifica si el producto existe
    --------------------------------------------------------
    FUNCTION F_EXISTE_PRODUCTO
    (
        p_product_id IN SKU.product_id%TYPE
    )
    RETURN NUMBER
    IS
        v_cantidad NUMBER;
    BEGIN

        SELECT COUNT(*)
        INTO v_cantidad
        FROM SKU
        WHERE product_id = p_product_id;

        IF v_cantidad > 0 THEN
            RETURN 1;
        ELSE
            RETURN 0;
        END IF;

    END F_EXISTE_PRODUCTO;


    --------------------------------------------------------
    -- FUNCIÓN PÚBLICA
    -- Valida que el GTIN sea numérico y tenga entre
    -- 8 y 14 caracteres
    --------------------------------------------------------
    FUNCTION F_VALIDAR_FORMATO_GTIN
    (
        p_gtin IN PRODUCTOS_GTIN.gtin%TYPE
    )
    RETURN NUMBER
    IS
    BEGIN

        IF p_gtin IS NULL THEN
            RETURN 0;
        END IF;

        IF LENGTH(TRIM(p_gtin)) < 8
           OR LENGTH(TRIM(p_gtin)) > 14 THEN

            RETURN 0;

        END IF;

        IF REGEXP_LIKE(TRIM(p_gtin), '^[0-9]+$') THEN
            RETURN 1;
        ELSE
            RETURN 0;
        END IF;

    END F_VALIDAR_FORMATO_GTIN;


    --------------------------------------------------------
    -- PROCEDIMIENTO
    -- Cambia un GTIN de un producto a otro
    --------------------------------------------------------
    PROCEDURE PD_REASIGNAR_GTIN
    (
        p_product_id_actual IN PRODUCTOS_GTIN.product_id%TYPE,
        p_product_id_nuevo  IN PRODUCTOS_GTIN.product_id%TYPE,
        p_gtin              IN PRODUCTOS_GTIN.gtin%TYPE
    )
    IS
        v_asociacion_existe NUMBER;
    BEGIN

        IF F_EXISTE_PRODUCTO(p_product_id_actual) = 0 THEN

            RAISE_APPLICATION_ERROR(
                -20022,
                'El producto actual no existe.'
            );

        END IF;

        IF F_EXISTE_PRODUCTO(p_product_id_nuevo) = 0 THEN

            RAISE_APPLICATION_ERROR(
                -20023,
                'El producto nuevo no existe.'
            );

        END IF;

        IF p_product_id_actual = p_product_id_nuevo THEN

            RAISE_APPLICATION_ERROR(
                -20024,
                'El producto actual y el nuevo son iguales.'
            );

        END IF;

        SELECT COUNT(*)
        INTO v_asociacion_existe
        FROM PRODUCTOS_GTIN
        WHERE product_id = p_product_id_actual
          AND gtin = TRIM(p_gtin);

        IF v_asociacion_existe = 0 THEN

            RAISE_APPLICATION_ERROR(
                -20025,
                'El GTIN no está asociado al producto actual.'
            );

        END IF;

        UPDATE PRODUCTOS_GTIN
        SET product_id = p_product_id_nuevo
        WHERE product_id = p_product_id_actual
          AND gtin = TRIM(p_gtin);

        COMMIT;

        DBMS_OUTPUT.PUT_LINE(
            'GTIN reasignado correctamente al producto ' ||
            p_product_id_nuevo || '.'
        );

    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK;
            RAISE;

    END PD_REASIGNAR_GTIN;


