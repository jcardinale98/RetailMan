        v_count NUMBER;
    BEGIN
        SELECT COUNT(*)
        INTO   v_count
        FROM   MARCA
        WHERE  brand_id = p_brand_id;

        RETURN v_count; -- 0 = no existe, 1 = existe
    END FN_MARCA_EXISTE;


    ----------------------------------------------------------------------------
    FUNCTION FN_MARCA_DUPLICADA (
        p_manufacturer_id IN MARCA.manufacturer_id%TYPE,
        p_name            IN MARCA.name%TYPE,
        p_excluir_id      IN MARCA.brand_id%TYPE DEFAULT NULL
    ) RETURN NUMBER IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*)
        INTO   v_count
        FROM   MARCA
        WHERE      manufacturer_id = p_manufacturer_id
               AND UPPER(TRIM(name)) = UPPER(TRIM(p_name))
               AND ( p_excluir_id IS NULL
                     OR brand_id <> p_excluir_id );

        RETURN v_count; -- 0 = no hay duplicado, >0 = ya existe
    END FN_MARCA_DUPLICADA;


    ----------------------------------------------------------------------------
    PROCEDURE PR_CREAR_MARCA (
        p_manufacturer_id IN  MARCA.manufacturer_id%TYPE,
        p_name            IN  MARCA.name%TYPE,
        p_status          IN  MARCA.status%TYPE DEFAULT 'ACTIVE',
        p_new_id          OUT MARCA.brand_id%TYPE
    ) IS
    BEGIN
        IF p_name IS NULL OR TRIM(p_name) IS NULL THEN
            RAISE_APPLICATION_ERROR(-20005, 'El nombre de la marca es obligatorio.');
        END IF;

        -- La marca debe poderse asociar a un fabricante -> se valida que exista
        IF PKG_FABRICANTE.FN_FABRICANTE_EXISTE(p_manufacturer_id) = 0 THEN
