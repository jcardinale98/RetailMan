        WHERE retailer_id = p_retailer_id
          AND market_id = p_market_id;

        COMMIT;
        DBMS_OUTPUT.PUT_LINE('Mercado desasociado correctamente del retailer.');
    EXCEPTION
        WHEN OTHERS THEN
