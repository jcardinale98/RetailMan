        IF p_code IS NULL OR TRIM(p_code) IS NULL THEN
            RAISE_APPLICATION_ERROR(-21002, 'Debe indicar el codigo del retailer.');
        END IF;

        IF p_name IS NULL OR TRIM(p_name) IS NULL THEN
            RAISE_APPLICATION_ERROR(-21003, 'Debe indicar el nombre del retailer.');
        END IF;

        IF FN_RETAILER_DUPLICADO(p_code, p_retailer_id) > 0 THEN
            RAISE_APPLICATION_ERROR(-21005, 'Ya existe otro retailer con ese codigo.');
        END IF;

        IF p_status NOT IN ('ACTIVE', 'INACTIVE') THEN
            RAISE_APPLICATION_ERROR(-21007, 'El estado debe ser ACTIVE o INACTIVE.');
        END IF;

        UPDATE RETAILER
        SET code   = UPPER(TRIM(p_code)),
            name   = TRIM(p_name),
            status = p_status
        WHERE retailer_id = p_retailer_id;

        COMMIT;
        DBMS_OUTPUT.PUT_LINE('Retailer actualizado correctamente.');
    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK;
            RAISE;
    END PR_ACTUALIZAR_RETAILER;


