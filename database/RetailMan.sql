CREATE OR REPLACE PACKAGE BODY PKG_RETAILER AS

    ----------------------------------------------------------------------------
    FUNCTION FN_RETAILER_EXISTE (
        p_retailer_id IN RETAILER.retailer_id%TYPE
    ) RETURN NUMBER IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*)
        INTO v_count
        FROM RETAILER
        WHERE retailer_id = p_retailer_id;

        RETURN v_count;
    END FN_RETAILER_EXISTE;


    ----------------------------------------------------------------------------
    FUNCTION FN_RETAILER_DUPLICADO (
        p_code       IN RETAILER.code%TYPE,
        p_excluir_id IN RETAILER.retailer_id%TYPE DEFAULT NULL
    ) RETURN NUMBER IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*)
        INTO v_count
        FROM RETAILER
        WHERE UPPER(TRIM(code)) = UPPER(TRIM(p_code))
          AND (p_excluir_id IS NULL OR retailer_id <> p_excluir_id);

        RETURN v_count;
    END FN_RETAILER_DUPLICADO;


    ----------------------------------------------------------------------------
    FUNCTION FN_RETAILER_MERCADO_EXISTE (
        p_retailer_id IN RETAILER.retailer_id%TYPE,
        p_market_id   IN MERCADO.market_id%TYPE
    ) RETURN NUMBER IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*)
        INTO v_count
        FROM RETAILER_MERCADO
        WHERE retailer_id = p_retailer_id
          AND market_id = p_market_id;

        RETURN v_count;
    END FN_RETAILER_MERCADO_EXISTE;


    ----------------------------------------------------------------------------
    FUNCTION FN_RETAILER_TIENE_DEPENDENCIAS (
        p_retailer_id IN RETAILER.retailer_id%TYPE
    ) RETURN NUMBER IS
        v_tiendas   NUMBER;
        v_formatos  NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_tiendas
        FROM PUNTO_VENTA
        WHERE retailer_id = p_retailer_id;

        SELECT COUNT(*) INTO v_formatos
        FROM RETAILER_FORMATO
        WHERE retailer_id = p_retailer_id;

        RETURN v_tiendas + v_formatos;
    END FN_RETAILER_TIENE_DEPENDENCIAS;


    ----------------------------------------------------------------------------
    PROCEDURE PR_CREAR_RETAILER (
        p_market_id IN  MERCADO.market_id%TYPE,
        p_code      IN  RETAILER.code%TYPE,
        p_name      IN  RETAILER.name%TYPE,
        p_new_id    OUT RETAILER.retailer_id%TYPE
    ) IS
        v_mercado_existe NUMBER;
    BEGIN
        IF p_market_id IS NULL THEN
            RAISE_APPLICATION_ERROR(-21001, 'Debe indicar el mercado del retailer.');
        END IF;

        IF p_code IS NULL OR TRIM(p_code) IS NULL THEN
            RAISE_APPLICATION_ERROR(-21002, 'Debe indicar el codigo del retailer.');
        END IF;

        IF p_name IS NULL OR TRIM(p_name) IS NULL THEN
            RAISE_APPLICATION_ERROR(-21003, 'Debe indicar el nombre del retailer.');
        END IF;

        SELECT COUNT(*)
        INTO v_mercado_existe
        FROM MERCADO
        WHERE market_id = p_market_id;

        IF v_mercado_existe = 0 THEN
            RAISE_APPLICATION_ERROR(-21004, 'El mercado indicado no existe.');
        END IF;

        IF FN_RETAILER_DUPLICADO(p_code) > 0 THEN
            RAISE_APPLICATION_ERROR(-21005, 'Ya existe un retailer con ese codigo.');
        END IF;

        INSERT INTO RETAILER (
            code,
            name,
            status
        ) VALUES (
            UPPER(TRIM(p_code)),
            TRIM(p_name),
            'ACTIVE'
        ) RETURNING retailer_id INTO p_new_id;

        INSERT INTO RETAILER_MERCADO (
            retailer_id,
            market_id
        ) VALUES (
            p_new_id,
            p_market_id
        );

        COMMIT;
        DBMS_OUTPUT.PUT_LINE('Retailer registrado correctamente. ID: ' || p_new_id);
    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK;
            RAISE;
    END PR_CREAR_RETAILER;


    ----------------------------------------------------------------------------
    PROCEDURE PR_LEER_RETAILER (
        p_retailer_id IN  RETAILER.retailer_id%TYPE DEFAULT NULL,
        p_cursor      OUT SYS_REFCURSOR
    ) IS
    BEGIN
        OPEN p_cursor FOR
            SELECT
                r.retailer_id,
                r.code,
                r.name,
                r.status,
                rm.market_id,
                m.name AS mercado_nombre
            FROM RETAILER r
            LEFT JOIN RETAILER_MERCADO rm
                ON rm.retailer_id = r.retailer_id
            LEFT JOIN MERCADO m
                ON m.market_id = rm.market_id
            WHERE (p_retailer_id IS NULL OR r.retailer_id = p_retailer_id)
            ORDER BY r.name, m.name;
    END PR_LEER_RETAILER;


    ----------------------------------------------------------------------------
    PROCEDURE PR_ACTUALIZAR_RETAILER (
        p_retailer_id IN RETAILER.retailer_id%TYPE,
        p_code        IN RETAILER.code%TYPE,
        p_name        IN RETAILER.name%TYPE,
        p_status      IN RETAILER.status%TYPE
    ) IS
    BEGIN
        IF FN_RETAILER_EXISTE(p_retailer_id) = 0 THEN
            RAISE_APPLICATION_ERROR(-21006, 'El retailer indicado no existe.');
