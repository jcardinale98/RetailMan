    ----------------------------------------------------------------------------
    PROCEDURE PR_REPORTE_TIENDAS_RETAILER (
        p_retailer_id IN RETAILER.retailer_id%TYPE
    ) IS
        CURSOR c_tiendas IS
            SELECT
                pv.store_id,
                pv.name,
                pv.status,
                m.name AS mercado
            FROM PUNTO_VENTA pv
            INNER JOIN MERCADO m
                ON m.market_id = pv.market_id
            WHERE pv.retailer_id = p_retailer_id
            ORDER BY m.name, pv.name;

        v_nombre_retailer RETAILER.name%TYPE;
        v_total           NUMBER := 0;
    BEGIN
        IF FN_RETAILER_EXISTE(p_retailer_id) = 0 THEN
            RAISE_APPLICATION_ERROR(-21006, 'El retailer indicado no existe.');
        END IF;

        SELECT name
        INTO v_nombre_retailer
        FROM RETAILER
        WHERE retailer_id = p_retailer_id;

        DBMS_OUTPUT.PUT_LINE('Tiendas del retailer: ' || v_nombre_retailer);
        DBMS_OUTPUT.PUT_LINE('--------------------------------------------');

        FOR r_tienda IN c_tiendas LOOP
            DBMS_OUTPUT.PUT_LINE(
                r_tienda.store_id || ' | ' || r_tienda.name ||
                ' | ' || r_tienda.mercado || ' | ' || r_tienda.status
            );
            v_total := v_total + 1;
        END LOOP;

        IF v_total = 0 THEN
            DBMS_OUTPUT.PUT_LINE('(Sin tiendas registradas)');
        END IF;

        DBMS_OUTPUT.PUT_LINE('Total de tiendas: ' || v_total);
    END PR_REPORTE_TIENDAS_RETAILER;


    ----------------------------------------------------------------------------
    PROCEDURE PR_REPORTE_RETAILERS_POR_MERCADO IS

        CURSOR c_mercados IS
            SELECT market_id, name
            FROM MERCADO
            ORDER BY name;

        CURSOR c_retailers (p_market_id MERCADO.market_id%TYPE) IS
            SELECT
                r.retailer_id,
                r.code,
                r.name,
                r.status
            FROM RETAILER r
            INNER JOIN RETAILER_MERCADO rm
                ON rm.retailer_id = r.retailer_id
            WHERE rm.market_id = p_market_id
            ORDER BY r.name;

        v_total_retailers NUMBER;
    BEGIN
        FOR r_mercado IN c_mercados LOOP
            DBMS_OUTPUT.PUT_LINE('Mercado: ' || r_mercado.name);
            v_total_retailers := 0;

            FOR r_retailer IN c_retailers(r_mercado.market_id) LOOP
                DBMS_OUTPUT.PUT_LINE(
                    '   - [' || r_retailer.code || '] ' ||
                    r_retailer.name || ' (' || r_retailer.status || ')'
                );
                v_total_retailers := v_total_retailers + 1;
            END LOOP;

            IF v_total_retailers = 0 THEN
                DBMS_OUTPUT.PUT_LINE('   (Sin retailers registrados)');
            END IF;
        END LOOP;
    END PR_REPORTE_RETAILERS_POR_MERCADO;

END PKG_RETAILER;
