            SELECT
                m.brand_id,
                m.name,
                m.status,
                m.manufacturer_id,
                f.name AS fabricante_nombre
            FROM
                     MARCA m
                JOIN FABRICANTE f ON f.manufacturer_id = m.manufacturer_id
            WHERE
                ( p_brand_id IS NULL OR m.brand_id = p_brand_id )
            ORDER BY
                m.name;
    END PR_LEER_MARCA;


