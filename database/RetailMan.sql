        IF FN_MARCA_DUPLICADA(p_manufacturer_id, p_name) > 0 THEN
            RAISE_APPLICATION_ERROR(-20007, 'Ya existe una marca con ese nombre para el fabricante indicado.');
        END IF;

        IF p_status NOT IN ('ACTIVE', 'INACTIVE') THEN
            RAISE_APPLICATION_ERROR(-20009, 'El estado debe ser ACTIVE o INACTIVE.');
        END IF;

        INSERT INTO MARCA (
            manufacturer_id,
            name,
            status
        ) VALUES (
            p_manufacturer_id,
            TRIM(p_name),
            p_status
        ) RETURNING brand_id INTO p_new_id;

        COMMIT;
        DBMS_OUTPUT.PUT_LINE('Marca registrada correctamente. ID: ' || p_new_id);
    EXCEPTION
        WHEN OTHERS THEN
