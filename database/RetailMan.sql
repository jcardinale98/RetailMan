        PD_INSERTAR_GTIN_INTERNO(p_gtin2);
        PD_INSERTAR_GTIN_INTERNO(p_gtin3);

        COMMIT;

        DBMS_OUTPUT.PUT_LINE(
            'Los GTIN fueron registrados correctamente.'
        );

