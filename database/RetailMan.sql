------------------------------------------------------------------------------------------
-- CRUD RETAILER_MERCADO
-- ACTUALIZAR ASOCIACION RETAILER - MERCADO
-------------------------------------------------------------------------------------------

CREATE OR REPLACE PROCEDURE PR_ACTUALIZAR_RETAILER_MERCADO
(
    p_retailer_id       IN RETAILER.retailer_id%TYPE,
    p_market_id_actual  IN MERCADO.market_id%TYPE,
    p_market_id_nuevo   IN MERCADO.market_id%TYPE,
    p_resultado         OUT NUMBER
)
IS

    v_asociacion_actual NUMBER;
    v_mercado_nuevo     NUMBER;
    v_asociacion_nueva  NUMBER;
    v_puntos_venta      NUMBER;

BEGIN

    p_resultado := 0;


    ---------------------------------------------------------------------------
    -- VALIDAR CAMPOS OBLIGATORIOS
    ---------------------------------------------------------------------------

    IF p_retailer_id IS NULL THEN

        RAISE_APPLICATION_ERROR(
            -21100,
            'Debe indicar el retailer.'
        );

    END IF;


    IF p_market_id_actual IS NULL THEN

        RAISE_APPLICATION_ERROR(
            -21101,
            'Debe indicar el mercado actual.'
        );

    END IF;


    IF p_market_id_nuevo IS NULL THEN

        RAISE_APPLICATION_ERROR(
            -21102,
            'Debe indicar el nuevo mercado.'
        );

    END IF;


    ---------------------------------------------------------------------------
    -- VALIDAR QUE EXISTA LA ASOCIACION ACTUAL
    ---------------------------------------------------------------------------

    SELECT COUNT(*)
    INTO v_asociacion_actual
    FROM RETAILER_MERCADO
    WHERE retailer_id = p_retailer_id
      AND market_id = p_market_id_actual;


    IF v_asociacion_actual = 0 THEN

        RAISE_APPLICATION_ERROR(
            -21103,
            'La asociacion retailer-mercado actual no existe.'
        );

    END IF;


    ---------------------------------------------------------------------------
    -- VALIDAR QUE EXISTA EL NUEVO MERCADO
    ---------------------------------------------------------------------------

    SELECT COUNT(*)
    INTO v_mercado_nuevo
    FROM MERCADO
    WHERE market_id = p_market_id_nuevo;


    IF v_mercado_nuevo = 0 THEN

        RAISE_APPLICATION_ERROR(
            -21104,
            'El nuevo mercado indicado no existe.'
        );

    END IF;


    ---------------------------------------------------------------------------
    -- VALIDAR QUE LA NUEVA ASOCIACION NO EXISTA
    ---------------------------------------------------------------------------

    SELECT COUNT(*)
    INTO v_asociacion_nueva
    FROM RETAILER_MERCADO
    WHERE retailer_id = p_retailer_id
      AND market_id = p_market_id_nuevo;


    IF v_asociacion_nueva > 0 THEN

        RAISE_APPLICATION_ERROR(
            -21105,
            'El retailer ya se encuentra asociado con el nuevo mercado.'
        );

    END IF;


    ---------------------------------------------------------------------------
    -- VALIDAR PUNTOS DE VENTA
    ---------------------------------------------------------------------------

    SELECT COUNT(*)
    INTO v_puntos_venta
    FROM PUNTO_VENTA
    WHERE retailer_id = p_retailer_id
      AND market_id = p_market_id_actual;


    IF v_puntos_venta > 0 THEN

        RAISE_APPLICATION_ERROR(
            -21106,
            'No se puede actualizar la asociacion porque existen puntos de venta relacionados.'
        );

    END IF;


    ---------------------------------------------------------------------------
    -- ACTUALIZAR ASOCIACION
    ---------------------------------------------------------------------------

    UPDATE RETAILER_MERCADO
    SET market_id = p_market_id_nuevo
    WHERE retailer_id = p_retailer_id
      AND market_id = p_market_id_actual;


    IF SQL%FOUND THEN

        p_resultado := 1;

        COMMIT;

        DBMS_OUTPUT.PUT_LINE(
            'Asociacion retailer-mercado actualizada correctamente.'
        );

    ELSE

        p_resultado := 0;

    END IF;


EXCEPTION

    WHEN OTHERS THEN

        p_resultado := 0;

        ROLLBACK;

        RAISE;

END;
