CREATE OR REPLACE PROCEDURE PR_ACTUALIZAR_RETAILER_FORMATO
(
    p_retailer_format_id IN RETAILER_FORMATO.retailer_format_id%TYPE,
    p_retailer_id        IN RETAILER_FORMATO.retailer_id%TYPE,
    p_format_id          IN RETAILER_FORMATO.format_id%TYPE,
    p_name               IN RETAILER_FORMATO.name%TYPE,
    p_status             IN RETAILER_FORMATO.status%TYPE,
    p_resultado          OUT NUMBER
)
IS
    v_asociacion NUMBER;
    v_retailer   NUMBER;
    v_formato    NUMBER;
    v_repetido   NUMBER;
BEGIN
    p_resultado := 0;

    IF p_retailer_format_id IS NULL THEN
        RAISE_APPLICATION_ERROR(-20051, 'Debe indicar la asociacion retailer formato.');
    END IF;

    IF p_retailer_id IS NULL THEN
        RAISE_APPLICATION_ERROR(-20052, 'Debe indicar el retailer.');
    END IF;

    IF p_format_id IS NULL THEN
        RAISE_APPLICATION_ERROR(-20053, 'Debe indicar el formato comercial.');
    END IF;

    IF p_name IS NULL OR TRIM(p_name) IS NULL THEN
        RAISE_APPLICATION_ERROR(-20054, 'Debe indicar el nombre comercial de la asociacion.');
    END IF;

    IF p_status IS NULL THEN
        RAISE_APPLICATION_ERROR(-20055, 'Debe indicar el estado de la asociacion.');
    END IF;

    IF UPPER(p_status) <> 'ACTIVE'
       AND UPPER(p_status) <> 'INACTIVE' THEN
        RAISE_APPLICATION_ERROR(-20056, 'El estado debe ser ACTIVE o INACTIVE.');
    END IF;

    SELECT COUNT(*)
    INTO v_asociacion
    FROM RETAILER_FORMATO
    WHERE retailer_format_id = p_retailer_format_id;

    IF v_asociacion = 0 THEN
        RAISE_APPLICATION_ERROR(-20057, 'La asociacion retailer formato indicada no existe.');
    END IF;

    SELECT COUNT(*)
    INTO v_retailer
    FROM RETAILER
    WHERE retailer_id = p_retailer_id;

    IF v_retailer = 0 THEN
        RAISE_APPLICATION_ERROR(-20058, 'El retailer indicado no existe.');
    END IF;

    SELECT COUNT(*)
    INTO v_formato
    FROM FORMATO
    WHERE format_id = p_format_id;

    IF v_formato = 0 THEN
        RAISE_APPLICATION_ERROR(-20059, 'El formato comercial indicado no existe.');
    END IF;

    SELECT COUNT(*)
    INTO v_repetido
    FROM RETAILER_FORMATO
    WHERE retailer_id = p_retailer_id
      AND format_id = p_format_id
      AND UPPER(name) = UPPER(TRIM(p_name))
      AND retailer_format_id <> p_retailer_format_id;

    IF v_repetido > 0 THEN
        RAISE_APPLICATION_ERROR(
            -20060,
            'Ya existe una asociacion con el mismo retailer, formato y nombre.'
        );
    END IF;

    UPDATE RETAILER_FORMATO
    SET retailer_id = p_retailer_id,
        format_id   = p_format_id,
        name        = TRIM(p_name),
        status      = UPPER(p_status)
    WHERE retailer_format_id = p_retailer_format_id;

    IF SQL%FOUND THEN
        p_resultado := 1;
    ELSE
        p_resultado := 0;
    END IF;

    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        p_resultado := 0;
        ROLLBACK;
        RAISE;
END;
/

CREATE OR REPLACE PROCEDURE PR_ELIMINAR_RETAILER_FORMATO
(
    p_retailer_format_id IN RETAILER_FORMATO.retailer_format_id%TYPE,
    p_resultado          OUT NUMBER
)
IS
    v_asociacion NUMBER;
BEGIN
    p_resultado := 0;

    IF p_retailer_format_id IS NULL THEN
        RAISE_APPLICATION_ERROR(-20061, 'Debe indicar la asociacion retailer formato.');
    END IF;

    SELECT COUNT(*)
    INTO v_asociacion
    FROM RETAILER_FORMATO
    WHERE retailer_format_id = p_retailer_format_id;

    IF v_asociacion = 0 THEN
        RAISE_APPLICATION_ERROR(
            -20062,
            'La asociacion retailer formato indicada no existe.'
        );
    END IF;

    UPDATE RETAILER_FORMATO
    SET status = 'INACTIVE'
    WHERE retailer_format_id = p_retailer_format_id;

    IF SQL%FOUND THEN
        p_resultado := 1;
    ELSE
        p_resultado := 0;
    END IF;

    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        p_resultado := 0;
        ROLLBACK;
        RAISE;
END;
