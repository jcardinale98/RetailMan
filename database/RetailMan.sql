    -- Consulta productos y GTIN pertenecientes a una marca
    --------------------------------------------------------
    PROCEDURE PD_CONSULTAR_GTIN_MARCA
    (
        p_brand_id  IN MARCA.brand_id%TYPE,
        p_resultado OUT SYS_REFCURSOR
    )
    IS
        v_marca_existe NUMBER;
    BEGIN

        SELECT COUNT(*)
        INTO v_marca_existe
        FROM MARCA
        WHERE brand_id = p_brand_id;

        IF v_marca_existe = 0 THEN
            RAISE_APPLICATION_ERROR(
                -20021,
                'La marca indicada no existe.'
            );
        END IF;

        OPEN p_resultado FOR
            SELECT
                M.brand_id,
                M.name AS brand_name,
                S.product_id,
                S.sku_code,
                S.description,
                PG.gtin
            FROM MARCA M
            INNER JOIN SKU S
                ON M.brand_id = S.brand_id
            INNER JOIN PRODUCTOS_GTIN PG
                ON S.product_id = PG.product_id
            WHERE M.brand_id = p_brand_id
            ORDER BY
                S.description,
                PG.gtin;

    END PD_CONSULTAR_GTIN_MARCA;


    --------------------------------------------------------
    -- Reporte mediante cursor explícito
    --------------------------------------------------------
    PROCEDURE PD_REPORTE_GTIN_PRODUCTOS
    IS

        CURSOR c_productos_gtin IS
            SELECT
                S.product_id,
                S.sku_code,
                S.description,
                PG.gtin
            FROM SKU S
            INNER JOIN PRODUCTOS_GTIN PG
                ON S.product_id = PG.product_id
            ORDER BY
                S.product_id,
                PG.gtin;

        v_product_id  SKU.product_id%TYPE;
        v_sku_code    SKU.sku_code%TYPE;
        v_description SKU.description%TYPE;
        v_gtin        PRODUCTOS_GTIN.gtin%TYPE;

        v_cantidad NUMBER := 0;

    BEGIN

        OPEN c_productos_gtin;

        LOOP

            FETCH c_productos_gtin
            INTO
                v_product_id,
                v_sku_code,
                v_description,
                v_gtin;

            EXIT WHEN c_productos_gtin%NOTFOUND;

            v_cantidad := v_cantidad + 1;

            DBMS_OUTPUT.PUT_LINE(
                'Producto ID: ' || v_product_id ||
                ' | Código: ' || v_sku_code ||
                ' | Descripción: ' || v_description ||
                ' | GTIN: ' || v_gtin
            );

        END LOOP;

        CLOSE c_productos_gtin;

        IF v_cantidad = 0 THEN
            DBMS_OUTPUT.PUT_LINE(
                'No existen productos con GTIN registrados.'
            );
        ELSE
            DBMS_OUTPUT.PUT_LINE(
                'Total de registros encontrados: ' || v_cantidad
            );
        END IF;

    END PD_REPORTE_GTIN_PRODUCTOS;

