CREATE OR REPLACE PACKAGE BODY PKG_FABRICANTE AS

    ----------------------------------------------------------------------------
    FUNCTION FN_FABRICANTE_EXISTE (
        p_manufacturer_id IN FABRICANTE.manufacturer_id%TYPE
    ) RETURN NUMBER IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*)
        INTO   v_count
        FROM   FABRICANTE
        WHERE  manufacturer_id = p_manufacturer_id;

        RETURN v_count; -- 0 = no existe, 1 = existe
    END FN_FABRICANTE_EXISTE;


    ----------------------------------------------------------------------------
    FUNCTION FN_FABRICANTE_DUPLICADO (
        p_name       IN FABRICANTE.name%TYPE,
        p_excluir_id IN FABRICANTE.manufacturer_id%TYPE DEFAULT NULL
    ) RETURN NUMBER IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*)
        INTO   v_count
        FROM   FABRICANTE
        WHERE      UPPER(TRIM(name)) = UPPER(TRIM(p_name))
               AND ( p_excluir_id IS NULL
                     OR manufacturer_id <> p_excluir_id );

        RETURN v_count; -- 0 = no hay duplicado, >0 = ya existe
    END FN_FABRICANTE_DUPLICADO;


    ----------------------------------------------------------------------------
    FUNCTION FN_FABRICANTE_TIENE_MARCAS (
        p_manufacturer_id IN FABRICANTE.manufacturer_id%TYPE
    ) RETURN NUMBER IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*)
        INTO   v_count
        FROM   MARCA
        WHERE  manufacturer_id = p_manufacturer_id;

        RETURN v_count; -- 0 = no tiene marcas, >0 = tiene marcas asociadas
    END FN_FABRICANTE_TIENE_MARCAS;


    ----------------------------------------------------------------------------
    PROCEDURE PR_CREAR_FABRICANTE (
        p_name         IN  FABRICANTE.name%TYPE,
        p_country_code IN  FABRICANTE.country_code%TYPE,
        p_new_id       OUT FABRICANTE.manufacturer_id%TYPE
    ) IS
    BEGIN
        IF p_name IS NULL OR TRIM(p_name) IS NULL THEN
            RAISE_APPLICATION_ERROR(-20001, 'El nombre del fabricante es obligatorio.');
        END IF;

        IF FN_FABRICANTE_DUPLICADO(p_name) > 0 THEN
            RAISE_APPLICATION_ERROR(-20002, 'Ya existe un fabricante registrado con ese nombre.');
        END IF;

        INSERT INTO FABRICANTE (
            name,
            country_code
        ) VALUES (
            TRIM(p_name),
            p_country_code
        ) RETURNING manufacturer_id INTO p_new_id;

        COMMIT;
        DBMS_OUTPUT.PUT_LINE('Fabricante registrado correctamente. ID: ' || p_new_id);
    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK;
            RAISE;
    END PR_CREAR_FABRICANTE;


    ----------------------------------------------------------------------------
    PROCEDURE PR_LEER_FABRICANTE (
        p_manufacturer_id IN  FABRICANTE.manufacturer_id%TYPE DEFAULT NULL,
        p_cursor          OUT SYS_REFCURSOR
    ) IS
    BEGIN
        OPEN p_cursor FOR
            SELECT
                manufacturer_id,
                name,
                country_code
            FROM
                FABRICANTE
            WHERE
                ( p_manufacturer_id IS NULL OR manufacturer_id = p_manufacturer_id )
            ORDER BY
                name;
    END PR_LEER_FABRICANTE;


    ----------------------------------------------------------------------------
    PROCEDURE PR_ACTUALIZAR_FABRICANTE (
        p_manufacturer_id IN FABRICANTE.manufacturer_id%TYPE,
        p_name            IN FABRICANTE.name%TYPE,
        p_country_code    IN FABRICANTE.country_code%TYPE
    ) IS
    BEGIN
        IF FN_FABRICANTE_EXISTE(p_manufacturer_id) = 0 THEN
            RAISE_APPLICATION_ERROR(-20003, 'El fabricante indicado no existe.');
        END IF;

        IF FN_FABRICANTE_DUPLICADO(p_name, p_manufacturer_id) > 0 THEN
            RAISE_APPLICATION_ERROR(-20002, 'Ya existe otro fabricante con ese nombre.');
        END IF;

        UPDATE FABRICANTE
        SET
            name         = TRIM(p_name),
            country_code = p_country_code
        WHERE
            manufacturer_id = p_manufacturer_id;

        COMMIT;
        DBMS_OUTPUT.PUT_LINE('Fabricante actualizado correctamente.');
    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK;
            RAISE;
    END PR_ACTUALIZAR_FABRICANTE;


    ----------------------------------------------------------------------------
    PROCEDURE PR_ELIMINAR_FABRICANTE (
        p_manufacturer_id IN FABRICANTE.manufacturer_id%TYPE
    ) IS
    BEGIN
        IF FN_FABRICANTE_EXISTE(p_manufacturer_id) = 0 THEN
            RAISE_APPLICATION_ERROR(-20003, 'El fabricante indicado no existe.');
        END IF;

        IF FN_FABRICANTE_TIENE_MARCAS(p_manufacturer_id) > 0 THEN
            RAISE_APPLICATION_ERROR(-20004, 'No se puede eliminar: el fabricante tiene marcas asociadas.');
        END IF;

        DELETE FROM FABRICANTE
        WHERE manufacturer_id = p_manufacturer_id;

        COMMIT;
        DBMS_OUTPUT.PUT_LINE('Fabricante eliminado correctamente.');
    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK;
            RAISE;
    END PR_ELIMINAR_FABRICANTE;


    ----------------------------------------------------------------------------    
    PROCEDURE PR_REPORTE_MARCAS_FABRICANTE (
        p_manufacturer_id IN FABRICANTE.manufacturer_id%TYPE
    ) IS
        CURSOR c_marcas IS
            SELECT brand_id, name, status
            FROM   MARCA
            WHERE  manufacturer_id = p_manufacturer_id
            ORDER BY name;

        v_nombre_fabricante FABRICANTE.name%TYPE;
        v_total             NUMBER := 0;
    BEGIN
        IF FN_FABRICANTE_EXISTE(p_manufacturer_id) = 0 THEN
            RAISE_APPLICATION_ERROR(-20003, 'El fabricante indicado no existe.');
        END IF;

        SELECT name INTO v_nombre_fabricante
        FROM   FABRICANTE
        WHERE  manufacturer_id = p_manufacturer_id;

        DBMS_OUTPUT.PUT_LINE('Marcas del fabricante: ' || v_nombre_fabricante);
        DBMS_OUTPUT.PUT_LINE('--------------------------------------------');

        FOR r_marca IN c_marcas LOOP
            DBMS_OUTPUT.PUT_LINE(
                r_marca.brand_id || ' | ' || r_marca.name || ' | ' || r_marca.status
            );
            v_total := v_total + 1;
        END LOOP;

        IF v_total = 0 THEN
            DBMS_OUTPUT.PUT_LINE('(Sin marcas registradas)');
        END IF;

        DBMS_OUTPUT.PUT_LINE('Total de marcas: ' || v_total);
    END PR_REPORTE_MARCAS_FABRICANTE;

END PKG_FABRICANTE;
