            DBMS_OUTPUT.PUT_LINE(
                'El producto no tenía GTIN registrados.'
            );

        ELSE

            DBMS_OUTPUT.PUT_LINE(
                'Cantidad de GTIN eliminados: ' || p_resultado
            );

        END IF;

    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK;
            p_resultado := 0;
            RAISE;

    END PD_ELIMINAR_GTIN_PRODUCTO;


