                IF F_VALIDAR_FORMATO_GTIN(p_gtin) = 0 THEN

                    RAISE_APPLICATION_ERROR(
                        -20027,
                        'El GTIN ' || p_gtin ||
                        ' no tiene un formato válido.'
                    );

                END IF;

                SELECT COUNT(*)
                INTO v_existe
                FROM PRODUCTOS_GTIN
                WHERE gtin = TRIM(p_gtin);

